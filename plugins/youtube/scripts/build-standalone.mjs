#!/usr/bin/env node
// Build a single self-contained youtube.ts plugin:
// inlines meriyah.min.mjs, astring.mjs, yt.solver.core.js as strings, plus the
// extractor logic (index.ts + nsig.ts sources merged).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const yt = fileURLToPath(new URL("../", import.meta.url));

const esc = (s) => s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");

const meriyahSrc = readFileSync(yt + "node_modules/meriyah/dist/meriyah.min.mjs", "utf8");
const astringSrc = readFileSync(yt + "node_modules/astring/dist/astring.mjs", "utf8");
const solver = readFileSync(yt + "solver-source.ts", "utf8");
// solver-source.ts holds the raw JS with `\` -> \` and `$` -> \$ template escapes; unescape to recover the real JS.
const solverRaw = /SOLVER_SOURCE = `([\s\S]*)`;\s*$/.exec(solver)[1]
  .replace(/\\`/g, "`")
  .replace(/\\\$/g, "$")
  .replace(/\\\\/g, "\\");
const solverCode = solverRaw;

const indexSrc = readFileSync(yt + "index.ts", "utf8");
const nsigSrc = readFileSync(yt + "nsig.ts", "utf8");

// astring.mjs: strip export keywords, keep top-level consts/functions
let astringBody = astringSrc.replace(/^export (const|function|let) /gm, "$1 ");
astringBody = astringBody.replace(/export \{[^}]*\};?\s*$/, "");
// meriyah minified: strip the final export{...}
const meriyahBody = meriyahSrc.replace(/export\{[^}]*\};?\s*$/, "");

// nsig.ts: drop the imports; replace loadSolver body with inline construction
let nsig = nsigSrc
  .replace(
    'import { createRequire } from "node:module";\nimport { SOLVER_SOURCE } from "./solver-source.ts";\n\nconst require = createRequire(import.meta.url);\n',
    "",
  )
  .replace(
    'import { createRequire } from "node:module";\nimport { SOLVER_SOURCE } from "./solver-source.ts";\n\nconst require = createRequire(import.meta.url);\n\n',
    "",
  )
  .replace(/^import { SOLVER_SOURCE } from "\.\/solver-source\.ts";\n/m, "")
  .replace(/^import { createRequire } from "node:module";\n/m, "")
  .replace(/^const require = createRequire\(import\.meta\.url\);\n/m, "");
const loadSolverRe = /function loadSolver\(\):[\s\S]*?\n}\n/;
nsig = nsig.replace(loadSolverRe, `function loadSolver(): NonNullable<typeof solverState> {
  const INLINED = (() => {
    const m = new Function(ESC_MERIYAH + "\\n;return { parse: Gt, parseModule: _t, parseScript: zt, version: Yt, isParseError: x };")();
    const a = new Function(ESC_ASTRING + "\\n;return { generate };")();
    return { m, a };
  })();
  const factory = new Function("meriyah", "astring", \`"use strict";\\n\${SOLVER_CODE}\\nreturn jsc;\`);
  const jsc = factory(INLINED.m, INLINED.a) as (input: unknown) => SolverOutput;
  solverState = { jsc, cache: new Map() };
  return solverState;
}
`);

// index.ts: drop the nsig import (merged below)
const index = indexSrc.replace('import { solveNChallenges, encipheredN, applyN } from "./nsig.ts";\n', "");

const bundle = `/* SINGLE-FILE BUNDLE of the Tidepull YouTube plugin.
 * Auto-generated by scripts/build-standalone.mjs — do not edit by hand.
 * Inlines: meriyah (LGPL), astring (MIT), yt-dlp ejs solver core (Unlicense).
 */
const SOLVER_CODE = \`${esc(solverCode)}\`;
const ESC_MERIYAH = \`${esc(meriyahBody)}\`;
const ESC_ASTRING = \`${esc(astringBody)}\`;

${nsig}

${index}
`;

writeFileSync(yt + "dist-youtube.ts", bundle);
console.log(`wrote dist-youtube.ts (${bundle.length} bytes)`);
